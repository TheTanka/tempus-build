#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = ["picosvg>=0.23"]
# ///
"""Convert an SVG logo into Android adaptive-icon VectorDrawables.

Outputs (under <out>/res/drawable/):
  ic_launcher_foreground.xml  logo centered inside the 66dp safe zone
  ic_launcher_background.xml  solid background colour
  ic_launcher_monochrome.xml  logo silhouette for Android 13+ themed icons
  ic_splash_logo.xml          same as foreground, used by the splash screen
and <out>/preview.svg (launcher-style circle mask) for a visual check.

Only solid fills are supported. Gradients, embedded images and text make the
script fail on purpose instead of silently producing a broken icon.
"""

from __future__ import annotations

import argparse
import math
import re
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path
from typing import NoReturn

from picosvg.svg import SVG

CANVAS = 108.0  # adaptive icon canvas in dp
SAFE_RADIUS = 33.0  # 66dp safe-zone diameter
VISIBLE = 72.0  # visible area after launcher masking

SVG_NS = "http://www.w3.org/2000/svg"
DROP_TAGS = {"metadata", "title", "desc", "namedview"}

NAMED_COLORS = {
    "black": "000000",
    "white": "FFFFFF",
    "red": "FF0000",
    "green": "008000",
    "blue": "0000FF",
}


@dataclass
class Shape:
    d: str
    rgb: str  # RRGGBB
    alpha: float
    evenodd: bool
    x0: float
    y0: float
    x1: float
    y1: float


def fail(msg: str) -> NoReturn:
    print("svg2icons: " + msg, file=sys.stderr)
    sys.exit(1)


def local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def is_hidden(el: ET.Element) -> bool:
    if el.get("display", "").strip() == "none":
        return True
    if el.get("visibility", "").strip() == "hidden":
        return True
    style = el.get("style", "").replace(" ", "")
    return "display:none" in style or "visibility:hidden" in style


def strip_hidden(root: ET.Element) -> None:
    """Remove hidden layers and editor metadata (Inkscape hides layers via style)."""
    for parent in list(root.iter()):
        for child in list(parent):
            if is_hidden(child) or local(child.tag) in DROP_TAGS:
                parent.remove(child)
                continue
            if not child.tag.startswith("{" + SVG_NS + "}"):
                # sodipodi/inkscape namespaced elements
                parent.remove(child)


def parse_color(value: str) -> str:
    v = value.strip().lower()
    if v in NAMED_COLORS:
        return NAMED_COLORS[v]
    m = re.fullmatch(r"#([0-9a-f]{3}|[0-9a-f]{6})", v)
    if not m:
        fail("unsupported fill '" + value + "' (only solid colours are supported)")
    h = m.group(1)
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return h.upper()


def load_shapes(svg_path: Path) -> list[Shape]:
    ET.register_namespace("", SVG_NS)
    root = ET.fromstring(svg_path.read_text(encoding="utf-8"))
    strip_hidden(root)
    cleaned = ET.tostring(root, encoding="unicode")

    try:
        pico = SVG.fromstring(cleaned).topicosvg()
    except ValueError as exc:
        fail("SVG cannot be simplified to plain paths: " + str(exc))

    shapes: list[Shape] = []
    for p in pico.shapes():
        fill = p.fill or "black"
        if fill == "none":
            continue
        alpha = float(p.fill_opacity) * float(p.opacity)
        if alpha <= 0:
            continue
        box = p.bounding_box()
        shapes.append(
            Shape(
                d=p.d,
                rgb=parse_color(fill),
                alpha=alpha,
                evenodd=p.fill_rule == "evenodd",
                x0=box.x,
                y0=box.y,
                x1=box.x + box.w,
                y1=box.y + box.h,
            )
        )
    if not shapes:
        fail("no visible filled shapes found in SVG")
    return shapes


def fit(shapes: list[Shape], radius: float) -> tuple[float, float, float]:
    """Scale + translate so every shape's bbox corner lies within `radius` of the canvas center."""
    cx = (min(s.x0 for s in shapes) + max(s.x1 for s in shapes)) / 2
    cy = (min(s.y0 for s in shapes) + max(s.y1 for s in shapes)) / 2
    far = max(
        math.hypot(x - cx, y - cy)
        for s in shapes
        for x in (s.x0, s.x1)
        for y in (s.y0, s.y1)
    )
    scale = radius / far
    return scale, CANVAS / 2 - scale * cx, CANVAS / 2 - scale * cy


def num(v: float) -> str:
    return f"{v:.4f}".rstrip("0").rstrip(".")


def argb(rgb: str, alpha: float = 1.0) -> str:
    return f"#{round(alpha * 255):02X}{rgb}"


def vector(body: list[str]) -> str:
    head = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by svg2icons.py, do not edit -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    return "\n".join(head + body + ["</vector>", ""])


def path_xml(s: Shape, color: str, indent: str) -> list[str]:
    lines = [indent + "<path", indent + '    android:fillColor="' + color + '"']
    if s.evenodd:
        lines.append(indent + '    android:fillType="evenOdd"')
    lines.append(indent + '    android:pathData="' + s.d + '" />')
    return lines


def group_xml(
    shapes: list[Shape], tf: tuple[float, float, float], mono: bool
) -> list[str]:
    scale, tx, ty = tf
    out = [
        "    <group",
        '        android:scaleX="' + num(scale) + '"',
        '        android:scaleY="' + num(scale) + '"',
        '        android:translateX="' + num(tx) + '"',
        '        android:translateY="' + num(ty) + '">',
    ]
    for s in shapes:
        color = argb("FFFFFF") if mono else argb(s.rgb, s.alpha)
        out += path_xml(s, color, "        ")
    out.append("    </group>")
    return out


def preview_svg(shapes: list[Shape], tf: tuple[float, float, float], bg: str) -> str:
    scale, tx, ty = tf
    off = (CANVAS - VISIBLE) / 2
    paths = []
    for s in shapes:
        rule = ' fill-rule="evenodd"' if s.evenodd else ""
        paths.append(
            f'    <path d="{s.d}" fill="#{s.rgb}" fill-opacity="{num(s.alpha)}"{rule}/>'
        )
    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{num(off)} {num(off)} {num(VISIBLE)} {num(VISIBLE)}">',
            '  <clipPath id="m"><circle cx="54" cy="54" r="36"/></clipPath>',
            '  <g clip-path="url(#m)">',
            f'  <rect width="108" height="108" fill="#{bg}"/>',
            f'  <g transform="translate({num(tx)} {num(ty)}) scale({num(scale)})">',
            *paths,
            "  </g>",
            "  </g>",
            "</svg>",
            "",
        ]
    )


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("svg", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument(
        "--bg", default="#000000", help="background colour (default: %(default)s)"
    )
    ap.add_argument(
        "--radius",
        type=float,
        default=30.0,
        help="max distance in dp from center to logo edge, safe zone is 33 (default: %(default)s)",
    )
    args = ap.parse_args()

    if not 0 < args.radius <= SAFE_RADIUS:
        fail("--radius must be in (0, " + num(SAFE_RADIUS) + "]")

    shapes = load_shapes(args.svg)
    tf = fit(shapes, args.radius)
    bg = parse_color(args.bg)

    drawable = args.out / "res" / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)

    fg = vector(group_xml(shapes, tf, mono=False))
    (drawable / "ic_launcher_foreground.xml").write_text(fg, encoding="utf-8")
    (drawable / "ic_splash_logo.xml").write_text(fg, encoding="utf-8")
    (drawable / "ic_launcher_monochrome.xml").write_text(
        vector(group_xml(shapes, tf, mono=True)), encoding="utf-8"
    )
    background = [
        "    <path",
        '        android:fillColor="' + argb(bg) + '"',
        '        android:pathData="M0,0h108v108h-108z" />',
    ]
    (drawable / "ic_launcher_background.xml").write_text(
        vector(background), encoding="utf-8"
    )
    (args.out / "preview.svg").write_text(preview_svg(shapes, tf, bg), encoding="utf-8")

    print(f"svg2icons: {len(shapes)} shapes, scale {num(tf[0])} -> {drawable}")


if __name__ == "__main__":
    main()
