#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = ["picosvg>=0.23"]
# ///
"""Convert an SVG logo into Android VectorDrawables for Tempus.

Outputs (under <out>/res/drawable/):
  ic_launcher_foreground.xml  logo centered inside the 66dp safe zone
  ic_launcher_background.xml  solid background colour
  ic_launcher_monochrome.xml  logo silhouette for Android 13+ themed icons
  ui_splash_screen.xml        splash: plain logo (on the black splash background)
  ic_toolbar_tempo.xml        round badge: toolbar, nav drawer, login screen
  logo.xml                    round badge (unused upstream, kept consistent)
  ic_splash_logo.xml          rounded tile: widget placeholder art + widget preview
and in <out>/:
  preview.svg                 launcher icon with circle mask
  preview-inapp.svg           badge and tile on light and dark app backgrounds

Only solid fills are supported. Gradients, embedded images and text make the
script fail on purpose instead of silently producing a broken icon.
"""

from __future__ import annotations

import argparse
import math
import re
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path
from typing import NoReturn

from picosvg.svg import SVG

CANVAS = 108.0  # adaptive icon canvas in dp
SAFE_RADIUS = 33.0  # 66dp safe-zone diameter
VISIBLE = 72.0  # visible area after launcher masking
TILE_CORNER = 18.0  # rounded tile corner, close to the widget's album-art rounding

CIRCLE_PATH = "M54,0A54,54 0 1,1 54,108A54,54 0 1,1 54,0Z"
TILE_PATH = (
    f"M{TILE_CORNER:g},0H{CANVAS - TILE_CORNER:g}"
    f"A{TILE_CORNER:g},{TILE_CORNER:g} 0 0,1 {CANVAS:g},{TILE_CORNER:g}"
    f"V{CANVAS - TILE_CORNER:g}"
    f"A{TILE_CORNER:g},{TILE_CORNER:g} 0 0,1 {CANVAS - TILE_CORNER:g},{CANVAS:g}"
    f"H{TILE_CORNER:g}"
    f"A{TILE_CORNER:g},{TILE_CORNER:g} 0 0,1 0,{CANVAS - TILE_CORNER:g}"
    f"V{TILE_CORNER:g}"
    f"A{TILE_CORNER:g},{TILE_CORNER:g} 0 0,1 {TILE_CORNER:g},0Z"
)

SPLASH_LAYER_LIST = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by svg2icons.py, do not edit -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item
        android:drawable="@drawable/ic_launcher_foreground"
        android:gravity="center" />
</layer-list>
"""

# Backgrounds for preview-inapp.svg (Tempus dark/light surfaces, widget day/night)
PREVIEW_BGS = [
    ("toolbar dark", "2A1235", "badge"),
    ("toolbar light", "FFFBFE", "badge"),
    ("widget day", "F2F2F2", "tile"),
    ("widget night", "1A1A1A", "tile"),
]

SVG_NS = "http://www.w3.org/2000/svg"
DROP_TAGS = {"metadata", "title", "desc", "namedview"}

NAMED_COLORS = {
    "black": "000000",
    "white": "FFFFFF",
    "red": "FF0000",
    "green": "008000",
    "blue": "0000FF",
}


@dataclass
class Shape:
    d: str
    rgb: str  # RRGGBB
    alpha: float
    evenodd: bool
    x0: float
    y0: float
    x1: float
    y1: float


def fail(msg: str) -> NoReturn:
    print("svg2icons: " + msg, file=sys.stderr)
    sys.exit(1)


def local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def is_hidden(el: ET.Element) -> bool:
    if el.get("display", "").strip() == "none":
        return True
    if el.get("visibility", "").strip() == "hidden":
        return True
    style = el.get("style", "").replace(" ", "")
    return "display:none" in style or "visibility:hidden" in style


def strip_hidden(root: ET.Element) -> None:
    """Remove hidden layers and editor metadata (Inkscape hides layers via style)."""
    for parent in list(root.iter()):
        for child in list(parent):
            if is_hidden(child) or local(child.tag) in DROP_TAGS:
                parent.remove(child)
                continue
            if not child.tag.startswith("{" + SVG_NS + "}"):
                # sodipodi/inkscape namespaced elements
                parent.remove(child)


def parse_color(value: str) -> str:
    v = value.strip().lower()
    if v in NAMED_COLORS:
        return NAMED_COLORS[v]
    m = re.fullmatch(r"#([0-9a-f]{3}|[0-9a-f]{6})", v)
    if not m:
        fail("unsupported fill '" + value + "' (only solid colours are supported)")
    h = m.group(1)
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return h.upper()


def load_shapes(svg_path: Path) -> list[Shape]:
    ET.register_namespace("", SVG_NS)
    root = ET.fromstring(svg_path.read_text(encoding="utf-8"))
    strip_hidden(root)
    cleaned = ET.tostring(root, encoding="unicode")

    try:
        pico = SVG.fromstring(cleaned).topicosvg()
    except ValueError as exc:
        fail("SVG cannot be simplified to plain paths: " + str(exc))

    shapes: list[Shape] = []
    for p in pico.shapes():
        fill = p.fill or "black"
        if fill == "none":
            continue
        alpha = float(p.fill_opacity) * float(p.opacity)
        if alpha <= 0:
            continue
        box = p.bounding_box()
        shapes.append(
            Shape(
                d=p.d,
                rgb=parse_color(fill),
                alpha=alpha,
                evenodd=p.fill_rule == "evenodd",
                x0=box.x,
                y0=box.y,
                x1=box.x + box.w,
                y1=box.y + box.h,
            )
        )
    if not shapes:
        fail("no visible filled shapes found in SVG")
    return shapes


def fit(shapes: list[Shape], radius: float) -> tuple[float, float, float]:
    """Scale + translate so every shape's bbox corner lies within `radius` of the canvas center."""
    cx = (min(s.x0 for s in shapes) + max(s.x1 for s in shapes)) / 2
    cy = (min(s.y0 for s in shapes) + max(s.y1 for s in shapes)) / 2
    far = max(
        math.hypot(x - cx, y - cy)
        for s in shapes
        for x in (s.x0, s.x1)
        for y in (s.y0, s.y1)
    )
    scale = radius / far
    return scale, CANVAS / 2 - scale * cx, CANVAS / 2 - scale * cy


def num(v: float) -> str:
    return f"{v:.4f}".rstrip("0").rstrip(".")


def argb(rgb: str, alpha: float = 1.0) -> str:
    return f"#{round(alpha * 255):02X}{rgb}"


def vector(body: list[str]) -> str:
    head = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by svg2icons.py, do not edit -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    return "\n".join(head + body + ["</vector>", ""])


def path_xml(s: Shape, color: str, indent: str) -> list[str]:
    lines = [indent + "<path", indent + '    android:fillColor="' + color + '"']
    if s.evenodd:
        lines.append(indent + '    android:fillType="evenOdd"')
    lines.append(indent + '    android:pathData="' + s.d + '" />')
    return lines


def group_xml(
    shapes: list[Shape], tf: tuple[float, float, float], mono: bool
) -> list[str]:
    scale, tx, ty = tf
    out = [
        "    <group",
        '        android:scaleX="' + num(scale) + '"',
        '        android:scaleY="' + num(scale) + '"',
        '        android:translateX="' + num(tx) + '"',
        '        android:translateY="' + num(ty) + '">',
    ]
    for s in shapes:
        color = argb("FFFFFF") if mono else argb(s.rgb, s.alpha)
        out += path_xml(s, color, "        ")
    out.append("    </group>")
    return out


def bg_xml(path: str, rgb: str) -> list[str]:
    return [
        "    <path",
        '        android:fillColor="' + argb(rgb) + '"',
        '        android:pathData="' + path + '" />',
    ]


def svg_logo_group(shapes: list[Shape], tf: tuple[float, float, float]) -> list[str]:
    scale, tx, ty = tf
    out = [f'  <g transform="translate({num(tx)} {num(ty)}) scale({num(scale)})">']
    for s in shapes:
        rule = ' fill-rule="evenodd"' if s.evenodd else ""
        out.append(
            f'    <path d="{s.d}" fill="#{s.rgb}" fill-opacity="{num(s.alpha)}"{rule}/>'
        )
    out.append("  </g>")
    return out


def preview_inapp_svg(
    shapes: list[Shape],
    badge_tf: tuple[float, float, float],
    tile_tf: tuple[float, float, float],
    bg: str,
) -> str:
    """Four panels: badge and tile on the backgrounds they really appear on."""
    panel = 160
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {panel * len(PREVIEW_BGS)} {panel}">'
    ]
    for i, (_label, panel_bg, kind) in enumerate(PREVIEW_BGS):
        x = i * panel
        shape_path, tf = (
            (CIRCLE_PATH, badge_tf) if kind == "badge" else (TILE_PATH, tile_tf)
        )
        off = (panel - CANVAS) / 2
        out += [
            f'<rect x="{x}" width="{panel}" height="{panel}" fill="#{panel_bg}"/>',
            f'<g transform="translate({num(x + off)} {num(off)})">',
            f'  <path d="{shape_path}" fill="#{bg}"/>',
            *svg_logo_group(shapes, tf),
            "</g>",
        ]
    out += ["</svg>", ""]
    return "\n".join(out)


def preview_svg(shapes: list[Shape], tf: tuple[float, float, float], bg: str) -> str:
    scale, tx, ty = tf
    off = (CANVAS - VISIBLE) / 2
    paths = []
    for s in shapes:
        rule = ' fill-rule="evenodd"' if s.evenodd else ""
        paths.append(
            f'    <path d="{s.d}" fill="#{s.rgb}" fill-opacity="{num(s.alpha)}"{rule}/>'
        )
    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{num(off)} {num(off)} {num(VISIBLE)} {num(VISIBLE)}">',
            '  <clipPath id="m"><circle cx="54" cy="54" r="36"/></clipPath>',
            '  <g clip-path="url(#m)">',
            f'  <rect width="108" height="108" fill="#{bg}"/>',
            f'  <g transform="translate({num(tx)} {num(ty)}) scale({num(scale)})">',
            *paths,
            "  </g>",
            "  </g>",
            "</svg>",
            "",
        ]
    )


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("svg", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument(
        "--bg", default="#000000", help="background colour (default: %(default)s)"
    )
    ap.add_argument(
        "--radius",
        type=float,
        default=30.0,
        help="launcher: max distance in dp from center to logo edge, safe zone is 33 (default: %(default)s)",
    )
    ap.add_argument(
        "--badge-radius",
        type=float,
        default=40.0,
        help="in-app round badge (disc radius 54): logo radius (default: %(default)s)",
    )
    ap.add_argument(
        "--tile-radius",
        type=float,
        default=36.0,
        help="widget tile (108 square): logo radius (default: %(default)s)",
    )
    args = ap.parse_args()

    if not 0 < args.radius <= SAFE_RADIUS:
        fail("--radius must be in (0, " + num(SAFE_RADIUS) + "]")
    for name in ("badge_radius", "tile_radius"):
        if not 0 < getattr(args, name) <= CANVAS / 2:
            fail("--" + name.replace("_", "-") + " must be in (0, 54]")

    shapes = load_shapes(args.svg)
    tf = fit(shapes, args.radius)
    badge_tf = fit(shapes, args.badge_radius)
    tile_tf = fit(shapes, args.tile_radius)
    bg = parse_color(args.bg)

    drawable = args.out / "res" / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)

    def write(name: str, content: str) -> None:
        (drawable / name).write_text(content, encoding="utf-8")

    # Launcher (adaptive icon layers)
    write("ic_launcher_foreground.xml", vector(group_xml(shapes, tf, mono=False)))
    write("ic_launcher_monochrome.xml", vector(group_xml(shapes, tf, mono=True)))
    write("ic_launcher_background.xml", vector(bg_xml("M0,0h108v108h-108z", bg)))

    # Splash: upstream points ui_splash_screen at ic_splash_logo, which the widget
    # also uses. Point the splash at the plain foreground so ic_splash_logo can
    # become a tile that also works on the light widget background.
    write("ui_splash_screen.xml", SPLASH_LAYER_LIST)

    # In-app: round badge (toolbar, drawer, login) and rounded tile (widget)
    badge = vector(bg_xml(CIRCLE_PATH, bg) + group_xml(shapes, badge_tf, mono=False))
    write("ic_toolbar_tempo.xml", badge)
    write("logo.xml", badge)
    write(
        "ic_splash_logo.xml",
        vector(bg_xml(TILE_PATH, bg) + group_xml(shapes, tile_tf, mono=False)),
    )

    (args.out / "preview.svg").write_text(preview_svg(shapes, tf, bg), encoding="utf-8")
    (args.out / "preview-inapp.svg").write_text(
        preview_inapp_svg(shapes, badge_tf, tile_tf, bg), encoding="utf-8"
    )

    print(f"svg2icons: {len(shapes)} shapes, scale {num(tf[0])} -> {drawable}")


if __name__ == "__main__":
    main()
